// A Terrazzo plugin that writes a Swift package's sources for iOS (ADR 0063, 0064). @terrazzo/plugin-swift writes
// color sets too, but reads dark from token.mode, which the resolver leaves at "." (ADR 0063), so this one asks the
// resolver for each theme at the inputs iOS fixes, and writes the same color set JSON with a light and a dark value:
//   Pts/Colors.xcassets/contentInverseBase.colorset/Contents.json
//   Pts/PtsColors.swift     public enum PtsColors { public static let contentInverseBase = Color(.contentInverseBase) }
// The asset names are the token path in lower camel case, so Xcode's generated asset symbols (.contentInverseBase)
// are the Swift names; PtsColors makes them public, since a package's generated symbols are internal.
// PtsTypography holds a text style per text/* token (ADR 0066): its family and weight, at the size of the iOS text
// style its $extensions name, scaled as Apple scales that style, so Dynamic Type follows; and its letter spacing, at
// the same share of the size as the token's. PtsFonts registers the bundled files (build-fonts.ts writes them).
// With a catalog option it also writes catalog/PtsCatalog.swift: each token's path, description, and what the docs
// show next to it, and this version's release, for the demo app's pages (ADR 0065), as its own target, PtsCatalog.
import type { Plugin } from "@terrazzo/parser";

export type Release = { version: string; date: string | null; notes: string[] };

type Options = {
  /** the semantic color ids to write, in this order */
  colors: string[];
  /** the text style ids (text.*) to write, in this order */
  text: string[];
  /** the font family each token's font stack starts with → the family name the bundled file registers */
  families: Record<string, string>;
  /** where a token keeps its iOS text style: $extensions[key].ios.textStyle (pts/ios-text-style checks it) */
  key: string;
  /** the inputs iOS fixes: every modifier but theme (ADR 0063) */
  fixed: Record<string, string>;
  /** write catalog/PtsCatalog.swift for the demo, with this release */
  catalog?: Release;
};

/** Apple's text styles at the default text size (Large), in points: the sizes Dynamic Type scales from */
export const APPLE_SIZES: Record<string, number> = {
  largeTitle: 34,
  title: 28,
  title2: 22,
  title3: 20,
  headline: 17,
  body: 17,
  callout: 16,
  subheadline: 15,
  footnote: 13,
  caption: 12,
  caption2: 11,
};

type Typography = { fontFamily: string[] | string; fontSize: { value: number }; fontWeight: number; letterSpacing: { value: number } };

/** A text style on iOS: the bundled family, Apple's size for its text style, the token's weight, and its tracking */
export const textStyle = (token: { $value: unknown; $extensions?: Record<string, any> }, id: string, families: Record<string, string>, key: string) => {
  const t = token.$value as Typography;
  const name = Array.isArray(t.fontFamily) ? t.fontFamily[0] : t.fontFamily;
  const family = families[name];
  if (!family) throw new Error(`${id} uses ${name}, which the package doesn't bundle`);
  const style = token.$extensions?.[key]?.ios?.textStyle as string;
  const size = APPLE_SIZES[style];
  if (!size) throw new Error(`${id} names no iOS text style`);
  // the token's letter spacing as a share of its own size, at Apple's size: -1.25px at 64px is -0.66pt at 34pt
  const tracking = Math.round((t.letterSpacing.value / t.fontSize.value) * size * 100) / 100;
  return { family, style, size, weight: t.fontWeight, tracking };
};

export const swiftName = (id: string) =>
  id
    .split(/[.-]/)
    .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join("");

// Color set components as Xcode writes them for 8-bit colors: "0xRR" per channel, alpha as a 0–1 decimal
const channel = (x: number) => `0x${Math.round(Math.min(1, Math.max(0, x)) * 255).toString(16).padStart(2, "0").toUpperCase()}`;
export const components = (value: unknown, id: string) => {
  const c = value as { colorSpace: string; components: number[]; alpha?: number };
  if (c?.colorSpace !== "srgb") throw new Error(`${id} is not an srgb color`);
  const [red, green, blue] = c.components.map(channel);
  return { alpha: (c.alpha ?? 1).toFixed(3), blue, green, red };
};

/** A color as the docs show it: #RRGGBB, then its opacity when it has one (#000000 · 50%) */
export const hexLabel = (value: unknown) => {
  const c = value as { hex: string; alpha?: number };
  return `${c.hex.toUpperCase()}${(c.alpha ?? 1) < 1 ? ` · ${Math.round((c.alpha ?? 1) * 100)}%` : ""}`;
};

const json = (data: unknown) => `${JSON.stringify(data, undefined, 2)}\n`;
// A Swift string literal: JSON's escapes are Swift's for the text the descriptions hold
const str = (s: string) => JSON.stringify(s);
const slashes = (id: string) => id.replaceAll(".", "/");
const HEADER = "// Autogenerated from @pts/tokens by packages/ios/plugin-ios.ts. Do not edit.";
const CATALOG = "Pts/Colors.xcassets";

export default function ios({ colors, text, families, key, fixed, catalog }: Options): Plugin {
  return {
    name: "pts-ios",
    async build({ resolver, outputFile }) {
      const light = resolver.apply({ ...fixed, theme: "light" });
      const dark = resolver.apply({ ...fixed, theme: "dark" });

      outputFile(`${CATALOG}/Contents.json`, json({ info: { author: "xcode", version: 1 } }));
      for (const id of colors) {
        const color = (tokens: typeof light) => ({ "color-space": "srgb", components: components(tokens[id]?.$value, id) });
        outputFile(
          `${CATALOG}/${swiftName(id)}.colorset/Contents.json`,
          json({
            colors: [
              { color: color(light), idiom: "universal" },
              { appearances: [{ appearance: "luminosity", value: "dark" }], color: color(dark), idiom: "universal" },
            ],
            info: { author: "xcode", version: 1 },
          }),
        );
      }

      const properties = colors
        .map((id) => {
          const doc = light[id]?.$description;
          return `${doc ? `    /// ${doc}\n` : ""}    public static let ${swiftName(id)} = Color(.${swiftName(id)})`;
        })
        .join("\n\n");
      outputFile(
        "Pts/PtsColors.swift",
        `${HEADER}

import SwiftUI

/// The semantic colors of Plain. Each one is a color set with a light and a dark value, so it follows the system's
/// appearance by itself.
public enum PtsColors {
${properties}
}
`,
      );

      const styles = text.map((id) => ({ id, ...textStyle(light[id]!, id, families, key) }));
      outputFile(
        "Pts/PtsTypography.swift",
        `${HEADER}

import CoreText
import SwiftUI
import UIKit

/// A text style of Plain: a bundled family and weight at the size of the iOS text style it follows, scaled by Dynamic
/// Type as Apple scales that style, and its letter spacing. Set it with \`.textStyle(_:)\`; register the fonts first
/// (\`PtsFonts.register()\`).
public struct PtsTextStyle: Sendable {
    public let family: String
    /// The size at the default text size (Large), Apple's for \`textStyle\`
    public let size: CGFloat
    public let textStyle: Font.TextStyle
    /// The weight, 100–900: a position on a variable font's weight axis, or the face of a static family
    public let weight: CGFloat
    public let tracking: CGFloat

    /// The font at a Dynamic Type size. Built from Core Text, since SwiftUI's \`.weight(_:)\` doesn't move a variable
    /// font's weight axis.
    public func font(for dynamicTypeSize: DynamicTypeSize = .large) -> Font {
        let traits = UITraitCollection(preferredContentSizeCategory: UIContentSizeCategory(dynamicTypeSize))
        let scaled = UIFontMetrics(forTextStyle: uiTextStyle).scaledValue(for: size, compatibleWith: traits)
        let attributes: [CFString: Any] = [
            kCTFontFamilyNameAttribute: family,
            kCTFontTraitsAttribute: [kCTFontWeightTrait: Self.weightTrait(weight)],
            kCTFontVariationAttribute: [0x7767_6874: weight], // 'wght'
        ]
        return Font(CTFontCreateWithFontDescriptor(CTFontDescriptorCreateWithAttributes(attributes as CFDictionary), scaled, nil))
    }

    // Core Text's weight trait for a 100–900 weight, so a static family picks its face: regular 0, bold 0.4
    private static func weightTrait(_ weight: CGFloat) -> CGFloat {
        [100: -0.8, 200: -0.6, 300: -0.4, 400: 0, 500: 0.23, 600: 0.3, 700: 0.4, 800: 0.56, 900: 0.62][Int(weight)] ?? 0
    }

    private var uiTextStyle: UIFont.TextStyle {
        switch textStyle {
        case .largeTitle: .largeTitle
        case .title: .title1
        case .title2: .title2
        case .title3: .title3
        case .headline: .headline
        case .body: .body
        case .callout: .callout
        case .subheadline: .subheadline
        case .footnote: .footnote
        case .caption: .caption1
        case .caption2: .caption2
        @unknown default: .body
        }
    }
}

/// The text styles of Plain. Sizes are Apple's for each style's iOS text style, not the web's (ADR 0066).
public enum PtsTypography {
${styles
  .map(({ id, family, style, size, weight, tracking }) => {
    const doc = light[id]?.$description;
    return `${doc ? `    /// ${doc} iOS: ${style}, ${size}pt.\n` : ""}    public static let ${swiftName(id.replace(/^text\./, ""))} = PtsTextStyle(family: ${str(family)}, size: ${size}, textStyle: .${style}, weight: ${weight}, tracking: ${tracking})`;
  })
  .join("\n\n")}
}

private struct TextStyleModifier: ViewModifier {
    let style: PtsTextStyle
    @Environment(\\.dynamicTypeSize) private var dynamicTypeSize

    func body(content: Content) -> some View {
        content.font(style.font(for: dynamicTypeSize)).tracking(style.tracking)
    }
}

extension View {
    /// Sets a Plain text style: its font at the current Dynamic Type size, and its letter spacing
    public func textStyle(_ style: PtsTextStyle) -> some View {
        modifier(TextStyleModifier(style: style))
    }
}
`,
      );
      outputFile(
        "Pts/PtsFonts.swift",
        `${HEADER}

import CoreText
import Foundation

/// The font files of Plain, bundled with the package (OFL; dist/licenses): ${[...new Set(Object.values(families))].join(", ")}.
public enum PtsFonts {
    private static let registered: Void = {
        let urls = Bundle.module.urls(forResourcesWithExtension: "ttf", subdirectory: "Fonts") ?? []
        CTFontManagerRegisterFontURLs(urls as CFArray, .process, true, nil)
    }()

    /// Registers the fonts for this process, once; call it before the first text style is drawn, in the app's init.
    public static func register() {
        _ = registered
    }
}
`,
      );

      if (!catalog) return;
      // PtsCatalog: per color, its path, description, and alias and hex in light and dark (the first token it points
      // to, e.g. color/neutral/950), for pages that list tokens like the docs; and the release the Home screen shows
      const entries = colors
        .map((id) => {
          const pair = (f: (tokens: typeof light) => string) => `[${str(f(light))}, ${str(f(dark))}]`;
          const alias = (tokens: typeof light) => slashes(tokens[id]?.aliasChain?.[0] ?? "");
          const hex = (tokens: typeof light) => hexLabel(tokens[id]?.$value);
          return `        Entry(path: ${str(slashes(id))}, description: ${str(light[id]?.$description ?? "")}, aliases: ${pair(alias)}, hex: ${pair(hex)}, color: PtsColors.${swiftName(id)}),`;
        })
        .join("\n");
      const typeEntries = styles
        .map(({ id, family, style, size, weight, tracking }) => {
          const name = swiftName(id.replace(/^text\./, ""));
          return `        TypeEntry(path: ${str(slashes(id))}, description: ${str(light[id]?.$description ?? "")}, detail: ${str(`${style} · ${size}pt · ${family} ${weight} · ${tracking}`)}, style: PtsTypography.${name}),`;
        })
        .join("\n");
      outputFile(
        "catalog/PtsCatalog.swift",
        `${HEADER}

import Pts
import SwiftUI

/// Every color PtsColors holds, with what the docs show next to it, and this version's release. For the demo app.
public enum PtsCatalog {
    /// A color: its path (content/inverse/base), description, and its alias and hex in light, then dark
    public struct Entry: Identifiable, Sendable {
        public let path: String
        public let description: String
        public let aliases: [String]
        public let hex: [String]
        public let color: Color
        public var id: String { path }
    }

    /// A text style: its path, description, and its iOS text style, size, family, weight, and tracking
    public struct TypeEntry: Identifiable, Sendable {
        public let path: String
        public let description: String
        public let detail: String
        public let style: PtsTextStyle
        public var id: String { path }
    }

    /// The version of @pts/ios this build holds
    public static let version = ${str(catalog.version)}
    /// The day its tag was made, when the tag is here
    public static let releaseDate: String? = ${catalog.date ? str(catalog.date) : "nil"}
    /// Its entries in the shared changelog, each starting New:, Fix:, or Breaking:
    public static let releaseNotes: [String] = [${catalog.notes.map(str).join(", ")}]
    /// The modifiers iOS follows; the rest are fixed (ADR 0063)
    public static let modifiers = ["theme"]

    public static let colors: [Entry] = [
${entries}
    ]

    public static let typography: [TypeEntry] = [
${typeEntries}
    ]
}
`,
      );
    },
  };
}
